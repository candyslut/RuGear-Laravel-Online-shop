<?php

namespace Database\Seeders;

use App\Models\Ticket;
use App\Models\User;
use Illuminate\Database\Seeder;

class TicketSeeder extends Seeder
{
    /**
     * Run the database seeds.
     */
    public function run(): void
    {
        $categories = [
            'Технический сбой',
            'Проблема с заказом',
            'Сотрудничество',
            'Пасхалки и идеи',
        ];

        $messages = [
            'Мышка перестала определяться после обновления драйверов.',
            'Заказ висит в обработке уже 4 дня.',
            'Клавиатура иногда отправляет двойные нажатия.',
            'Есть идея сделать кастомные кейкапы.',
            'После запуска игры монитор теряет сигнал.',
            'Не работает RGB подсветка на коврике.',
            'Хочу предложить партнерство по стримам.',
            'Микрофон в гарнитуре начал шуметь.',
            'Колесико мыши скрипит при прокрутке.',
            'Пришел не тот товар.',
            'Подставка под ноутбук приехала с царапинами.',
            'Сайт иногда зависает при оформлении заказа.',
            'Не могу войти в аккаунт после смены пароля.',
            'Хотелось бы видеть больше аксессуаров.',
            'Проблемы с оплатой через карту.',
            'Коробка была сильно повреждена.',
            'Не приходит письмо подтверждения.',
            'Есть баг в мобильной версии сайта.',
            'Кнопка оформления заказа не нажимается.',
            'Хотел бы уточнить сроки поставки.',
        ];

        $users = User::all();

        if ($users->isEmpty()) {
            return;
        }

        for ($i = 0; $i < 27; $i++) {

            $user = $users->random();

            Ticket::create([
                'name' => $user->name,
                'category' => $categories[array_rand($categories)],
                'content' => $messages[array_rand($messages)],
                'user_id' => $user->id,
                'created_at' => now()->subDays(rand(0, 30)),
                'updated_at' => now(),
            ]);
        }
    }
}
